const pool = require("../../../Config/db.poolingConnection");
const logger = require("../../../Config/logger.config");
const RESPONSE = require("../../../Utils/ResponseMessagesColllection");

/////////////////////////////////////////////////////////////////////////////////////////
// Get All Notifications Service
// Purpose : Fetch All Notifications Of Employee
/////////////////////////////////////////////////////////////////////////////////////////

const getAllNotifications = async (employeeId) => {
  let connection;

  try {
    // Get Database Connection
    connection = await pool.getConnection();

    /////////////////////////////////////////////////////////////////////////////
    // Fetch Notifications
    /////////////////////////////////////////////////////////////////////////////

    const query = `
     SELECT
    id,
    task_id,
    employee_id,
    title,
    message,
    is_read,
    created_at
    FROM notifications
    WHERE employee_id = ?
    ORDER BY id DESC
    `;

    const [notifications] = await connection.query(query, [employeeId]);

    /////////////////////////////////////////////////////////////////////////////
    // Success Response
    /////////////////////////////////////////////////////////////////////////////

    return {
      success: true,
      response_code: 200,
      message: RESPONSE.NOTIFICATIONS_FETCHED_SUCCESSFULLY,
      data: notifications,
    };
  } catch (error) {
    // Log Error
    logger.error(error.message);

    /////////////////////////////////////////////////////////////////////////////
    // Error Response
    /////////////////////////////////////////////////////////////////////////////

    return {
      success: false,
      response_code: 500,
      message: RESPONSE.SOMETHING_WENT_WRONG,
      data: [],
    };
  } finally {
    /////////////////////////////////////////////////////////////////////////////
    // Release Database Connection
    /////////////////////////////////////////////////////////////////////////////

    if (connection) connection.release();
  }
};

