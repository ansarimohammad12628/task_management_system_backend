const pool = require("../../../Config/db.poolingConnection");
const logger = require("../../../Config/logger.config");
const RESPONSE = require("../../../Utils/ResponseMessagesColllection");
const ExcelJS = require("exceljs");
const { Parser } = require("json2csv");

/////////////////////////////////////////////////////////////////////////////////////////
// Task Report Service
// Purpose : Fetch Task Report Based On Filters
/////////////////////////////////////////////////////////////////////////////////////////

const taskReport = async (filters) => {
  let connection;

  try {
    // Get Database Connection
    connection = await pool.getConnection();

    /////////////////////////////////////////////////////////////////////////////
    // Base Query
    /////////////////////////////////////////////////////////////////////////////

    let query = `
      SELECT
        t.id,
        CONCAT(e.first_name,' ',e.last_name) AS employee_name,
        t.title,
        t.description,
        t.priority,
        t.status,
        t.start_date,
        t.due_date
      FROM tasks t
      INNER JOIN employees e
      ON t.employee_id = e.id
      WHERE 1 = 1
    `;

    const values = [];

    /////////////////////////////////////////////////////////////////////////////
    // Status Filter
    /////////////////////////////////////////////////////////////////////////////

    if (
      filters.status &&
      filters.status !== "all"
    ) {
      query += ` AND t.status = ?`;
      values.push(filters.status);
    }

    /////////////////////////////////////////////////////////////////////////////
    // Employee Filter
    /////////////////////////////////////////////////////////////////////////////

    if (filters.employee_id) {
      query += ` AND t.employee_id = ?`;
      values.push(filters.employee_id);
    }

    /////////////////////////////////////////////////////////////////////////////
    // Order By Latest Task
    /////////////////////////////////////////////////////////////////////////////

    query += ` ORDER BY t.id DESC`;

    const [tasks] = await connection.query(query, values);

    /////////////////////////////////////////////////////////////////////////////
    // Success Response
    /////////////////////////////////////////////////////////////////////////////

    return {
      success: true,
      response_code: 200,
      message: RESPONSE.REPORT_FETCHED_SUCCESSFULLY,
      data: tasks,
    };
  } catch (error) {
    // Log Error
    logger.error(`Report Service => ${error.message}`);

    /////////////////////////////////////////////////////////////////////////////
    // Error Response
    /////////////////////////////////////////////////////////////////////////////

    return {
      success: false,
      response_code: 500,
      message: RESPONSE.SOMETHING_WENT_WRONG,
      data: [],
    };
  } finally {
    /////////////////////////////////////////////////////////////////////////////
    // Release Database Connection
    /////////////////////////////////////////////////////////////////////////////

    if (connection) {
      connection.release();
    }
  }
};



/////////////////////////////////////////////////////////////////////////////////////////
// Export Excel Service
// Purpose : Export Task Report In Excel Format
/////////////////////////////////////////////////////////////////////////////////////////

const exportExcel = async (req, res) => {
  let connection;

  try {
    // Get Database Connection
    connection = await pool.getConnection();

    /////////////////////////////////////////////////////////////////////////////
    // Fetch Tasks
    /////////////////////////////////////////////////////////////////////////////

    const [tasks] = await connection.query(`
      SELECT
        t.id,
        CONCAT(e.first_name,' ',e.last_name) AS employee_name,
        t.title,
        t.priority,
        t.status,
        t.start_date,
        t.due_date
      FROM tasks t
      INNER JOIN employees e
      ON t.employee_id = e.id
    `);

    /////////////////////////////////////////////////////////////////////////////
    // Create Excel Workbook
    /////////////////////////////////////////////////////////////////////////////

    const workbook = new ExcelJS.Workbook();

    const worksheet = workbook.addWorksheet("Task Report");

    /////////////////////////////////////////////////////////////////////////////
    // Define Worksheet Columns
    /////////////////////////////////////////////////////////////////////////////

    worksheet.columns = [
      { header: "ID", key: "id", width: 10 },
      { header: "Employee", key: "employee_name", width: 25 },
      { header: "Title", key: "title", width: 25 },
      { header: "Priority", key: "priority", width: 15 },
      { header: "Status", key: "status", width: 20 },
      { header: "Start Date", key: "start_date", width: 20 },
      { header: "Due Date", key: "due_date", width: 20 },
    ];

    /////////////////////////////////////////////////////////////////////////////
    // Add Data Into Worksheet
    /////////////////////////////////////////////////////////////////////////////

    worksheet.addRows(tasks);

    /////////////////////////////////////////////////////////////////////////////
    // Set Response Headers
    /////////////////////////////////////////////////////////////////////////////

    res.setHeader(
      "Content-Type",
      "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    );

    res.setHeader(
      "Content-Disposition",
      "attachment; filename=Task_Report.xlsx"
    );

    /////////////////////////////////////////////////////////////////////////////
    // Write Excel File
    /////////////////////////////////////////////////////////////////////////////

    await workbook.xlsx.write(res);

    res.end();

  } catch (error) {

    // Log Error
    console.log(error);

    /////////////////////////////////////////////////////////////////////////////
    // Error Response
    /////////////////////////////////////////////////////////////////////////////

    res.status(500).json({
      success: false,
      message: RESPONSE.SOMETHING_WENT_WRONG
    });

  } finally {

    /////////////////////////////////////////////////////////////////////////////
    // Release Database Connection
    /////////////////////////////////////////////////////////////////////////////

    if (connection) connection.release();

  }
};


